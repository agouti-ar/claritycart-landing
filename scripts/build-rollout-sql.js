// Concatenate authoritative migrations; only replace their outer transactions.
const fs=require('node:fs');const path=require('node:path');const {createHash}=require('node:crypto');
const root=path.resolve(__dirname,'..');
const sources=['migrations/001_chat_request_idempotency.sql','supabase/migrations/20261027142546_server_entitlements_and_monthly_quota.sql','supabase/migrations/20261027152654_widget_security_and_store_binding.sql'];
function migrationBody(source){
 const sql=source.replace(/\r\n/g,'\n');
 if((sql.match(/^begin;$/gm)||[]).length!==1||(sql.match(/^commit;$/gm)||[]).length!==1)throw new Error('Unexpected migration transaction layout');
 return sql.replace(/^begin;\n/m,'').replace(/^commit;\s*$/m,'').trimEnd();
}
function buildBundle(){
 const sections=sources.map(file=>{const raw=fs.readFileSync(path.join(root,file),'utf8');const sha=createHash('sha256').update(raw.replace(/\r\n/g,'\n')).digest('hex');return `-- SOURCE: ${file}\n-- SHA256 (LF-normalized): ${sha}\n${migrationBody(raw)}`;});
 return `-- GENERATED by node scripts/build-rollout-sql.js. Do not edit migration bodies here.
-- Apply manually only after backup, maintenance window and preflight approval.
-- Exactly 20 original test questions must remain unchanged and UNMAPPED.
-- Single atomic transaction; any error requires ROLLBACK before another attempt.
-- A completed or partial prior migration is rejected before DDL; this is not a repair script.
begin;
set local statement_timeout='60s';
set local lock_timeout='5s';
set local timezone='UTC';
do $$begin
 if to_regclass('public.chat_requests') is not null or to_regclass('public.cc_stores') is not null
 or to_regclass('public.cc_usage_periods') is not null or exists(select 1 from pg_namespace where nspname='cc_private')
 or exists(select 1 from information_schema.columns where table_schema='public' and table_name='questions' and column_name in ('cc_store_id','cc_request_id','cc_period_start')) then
  raise exception 'ROLLOUT_ALREADY_OR_PARTIALLY_APPLIED: inspect state; do not rerun blindly';
 end if;
 if to_regclass('public.questions') is null or to_regclass('auth.users') is null then raise exception 'ROLLOUT_SCHEMA_MISSING'; end if;
end;$$;
lock table public.questions in share row exclusive mode;
create temporary table cc_rollout_original_history on commit drop as
 select id,created_at,store_domain,question_text,product_context from public.questions;
do $$begin
 if (select count(*) from cc_rollout_original_history)<>20 then raise exception 'ROLLOUT_HISTORY_COUNT_CHANGED: expected 20; recheck preflight'; end if;
end;$$;

${sections.join('\n\n')}

-- Preservation assertions only; there is no legacy mapping step in this bundle.
do $$begin
 if (select count(*) from public.questions)<>20 or exists(
  select 1 from cc_rollout_original_history b full join public.questions q using(id)
  where b.id is null or q.id is null or
  row(b.created_at,b.store_domain,b.question_text,b.product_context) is distinct from
  row(q.created_at,q.store_domain,q.question_text,q.product_context)
 ) then raise exception 'ROLLOUT_HISTORY_CHANGED: transaction must roll back'; end if;
 if exists(select 1 from public.questions where cc_store_id is not null or cc_request_id is not null or cc_period_start is not null) then
  raise exception 'ROLLOUT_UNEXPECTED_LEGACY_MAPPING: transaction must roll back';
 end if;
end;$$;
select 'PASS' as history_preserved, count(*) as preserved_unmapped_questions from public.questions;
commit;
`;
}
if(require.main===module){const out=path.join(root,'scripts/supabase-stage1-4-rollout.sql');fs.writeFileSync(out,buildBundle());console.log('Generated '+path.relative(root,out)+' from three authoritative migration files.');}
module.exports={buildBundle,migrationBody,sources};
